def _format_redundancy_analysis(
    trajectories_with_redundancy: List[Tuple[Any, Any, Any, Any, Any]]
) -> str:
    """格式化冗余轨迹分析列表"""
    if not trajectories_with_redundancy:
        return "无轨迹冗余数据。"
    return "\n".join([
        f"// 轨迹_{idx}:\n"
        f"   - 冗余类型: {traj_item[1]}\n"
        f"   - 冗余步骤: {traj_item[2]}\n"
        f"   - 深度分析: {traj_item[3]}\n"
        f"   - 计划缺陷: {traj_item[4] if len(traj_item) > 4 and traj_item[4] else '无'}"
        for idx, traj_item in enumerate(trajectories_with_redundancy, start=1)
    ])


